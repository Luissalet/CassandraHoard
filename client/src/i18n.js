export function initialLang() {
  try {
    const saved = localStorage.getItem("cassandra-lang");
    if (saved === "es" || saved === "en") return saved;
  } catch {
    // storage may be blocked; fall back to the browser language
  }
  return (navigator.language || "es").toLowerCase().startsWith("es") ? "es" : "en";
}

export function saveLang(lang) {
  try {
    localStorage.setItem("cassandra-lang", lang);
  } catch {
    // not critical
  }
}

export function makeT(lang) {
  const dict = DICT[lang] || DICT.es;
  return (key, vars) => {
    let value = key.split(".").reduce((node, part) => (node && node[part] !== undefined ? node[part] : undefined), dict);
    if (value === undefined) return key;
    if (typeof value === "function") return value(vars);
    if (typeof value === "string" && vars) {
      for (const [name, v] of Object.entries(vars)) value = value.replaceAll(`{${name}}`, v);
    }
    return value;
  };
}
